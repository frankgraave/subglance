/**
 * The shell's icons, inline.
 *
 * Inline SVG rather than an icon font or a sprite sheet: five icons is not
 * worth a dependency, and `stroke: currentColor` is what lets a nav item's
 * hover colour carry its icon along without a second rule. Every one is
 * `aria-hidden` — the label beside it is the accessible name, and a decorative
 * icon that announces itself just makes a screen reader say everything twice.
 */

